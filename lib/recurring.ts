import { and, eq, gte } from "drizzle-orm";
import { db } from "@/db";
import { ledgerEntries, recurringRules } from "@/db/schema";
import { dateWithDay, toIsoDate } from "@/lib/dates";

function occurrenceDate(year: number, monthIndex: number, dayOfMonth: number) {
  return toIsoDate(dateWithDay(year, monthIndex, dayOfMonth));
}

/** Ensure confirmed ledger rows exist for enabled rules for current + next month. */
export async function materializeRecurring(now = new Date()) {
  const rules = await db
    .select()
    .from(recurringRules)
    .where(eq(recurringRules.enabled, true));

  const months = [
    { y: now.getUTCFullYear(), m: now.getUTCMonth() },
    { y: now.getUTCFullYear(), m: now.getUTCMonth() + 1 },
  ];

  for (const rule of rules) {
    for (const { y, m } of months) {
      const year = m > 11 ? y + Math.floor(m / 12) : y;
      const monthIndex = ((m % 12) + 12) % 12;
      const occursOn = occurrenceDate(year, monthIndex, rule.dayOfMonth);

      const existing = await db
        .select()
        .from(ledgerEntries)
        .where(
          and(
            eq(ledgerEntries.recurringRuleId, rule.id),
            eq(ledgerEntries.occursOn, occursOn),
          ),
        )
        .limit(1);

      if (existing.length > 0) continue;

      await db.insert(ledgerEntries).values({
        direction: rule.direction,
        method: rule.method,
        status: "confirmed",
        amountCents: rule.amountCents,
        occursOn,
        description: rule.name,
        categoryId: rule.categoryId,
        creditCardId: rule.creditCardId,
        recurringRuleId: rule.id,
        autoGenerated: true,
      });
    }
  }
}

/** Soft-cancel future auto rows when a rule is disabled. */
export async function cancelFutureMaterialized(ruleId: string, fromIso: string) {
  const rows = await db
    .select()
    .from(ledgerEntries)
    .where(
      and(
        eq(ledgerEntries.recurringRuleId, ruleId),
        eq(ledgerEntries.autoGenerated, true),
        gte(ledgerEntries.occursOn, fromIso),
      ),
    );

  for (const row of rows) {
    await db.delete(ledgerEntries).where(eq(ledgerEntries.id, row.id));
  }
}
