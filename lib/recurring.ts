import { eq } from "drizzle-orm";
import { db } from "@/db";
import { ledgerEntries, recurringRules } from "@/db/schema";

/** Recurring rules are templates only — they never create ledger rows. */
export async function listEnabledRules() {
  return db
    .select()
    .from(recurringRules)
    .where(eq(recurringRules.enabled, true));
}

/**
 * Remove leftover auto-materialized ledger rows from the old model.
 * Safe to call repeatedly.
 */
export async function purgeAutoMaterializedLedger() {
  await db
    .delete(ledgerEntries)
    .where(eq(ledgerEntries.autoGenerated, true));
}

export function sumRules(
  rules: { direction: "income" | "expense"; method: string; amountCents: number }[],
  direction: "income" | "expense",
) {
  return rules
    .filter((rule) => rule.direction === direction)
    .reduce((sum, rule) => sum + rule.amountCents, 0);
}

/** Cash-side recurring expenses (exclude card methods — those belong to cycle/limit math). */
export function sumRecurringCashExpenses(
  rules: { direction: "income" | "expense"; method: string; amountCents: number }[],
) {
  return rules
    .filter(
      (rule) =>
        rule.direction === "expense" &&
        rule.method !== "credit_card" &&
        rule.method !== "card_payment",
    )
    .reduce((sum, rule) => sum + rule.amountCents, 0);
}
