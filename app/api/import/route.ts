import { eq } from "drizzle-orm";
import { db } from "@/db";
import {
  creditCards,
  importBatches,
  installments,
  ledgerEntries,
  purchases,
} from "@/db/schema";
import { jsonError, jsonOk, unauthorizedIfNeeded } from "@/lib/api";
import { parseItauExtrato } from "@/lib/import/itau/extrato";
import { parseItauFatura } from "@/lib/import/itau/fatura";
import { extractPdfTextFromBuffer } from "@/lib/import/pdf-text";
import { buildInstallments } from "@/lib/purchases";

export async function POST(request: Request) {
  const unauthorized = await unauthorizedIfNeeded(request);
  if (unauthorized) return unauthorized;

  const form = await request.formData();
  const file = form.get("file");
  const type = String(form.get("type") || "");
  const creditCardId = String(form.get("creditCardId") || "") || null;

  if (!(file instanceof File)) return jsonError("file is required");
  if (type !== "extrato" && type !== "fatura") {
    return jsonError("type must be extrato or fatura");
  }

  const buffer = new Uint8Array(await file.arrayBuffer());
  let text: string;
  try {
    text = await extractPdfTextFromBuffer(buffer);
  } catch (error) {
    return jsonError(
      error instanceof Error ? error.message : "Failed to read PDF",
    );
  }

  if (type === "extrato") {
    const parsed = parseItauExtrato(text);
    const [batch] = await db
      .insert(importBatches)
      .values({
        type: "extrato",
        filename: file.name,
        warnings: parsed.warnings.join("\n"),
      })
      .returning();

    if (parsed.rows.length > 0) {
      await db.insert(ledgerEntries).values(
        parsed.rows.map((row) => ({
          direction: "expense" as const,
          method: row.method,
          status: "unconfirmed" as const,
          amountCents: row.amountCents,
          occursOn: row.occursOn,
          description: row.description,
          importBatchId: batch.id,
          autoGenerated: false,
        })),
      );
    }

    return jsonOk({
      batch,
      created: { ledgerEntries: parsed.rows.length, purchases: 0 },
      warnings: parsed.warnings,
    });
  }

  if (!creditCardId) {
    return jsonError("creditCardId is required for fatura import");
  }

  const [card] = await db
    .select()
    .from(creditCards)
    .where(eq(creditCards.id, creditCardId))
    .limit(1);
  if (!card) return jsonError("Credit card not found", 404);

  const parsed = parseItauFatura(text, new Date().getUTCFullYear());
  const cycleClose =
    parsed.cycleCloseDate ??
    `${new Date().getUTCFullYear()}-${String(new Date().getUTCMonth() + 1).padStart(2, "0")}-${String(card.cycleCloseDay).padStart(2, "0")}`;

  if (parsed.limitCents != null) {
    await db
      .update(creditCards)
      .set({ limitCents: parsed.limitCents })
      .where(eq(creditCards.id, card.id));
  }
  if (parsed.cycleCloseDate) {
    const day = Number(parsed.cycleCloseDate.slice(8, 10));
    if (day >= 1 && day <= 28) {
      await db
        .update(creditCards)
        .set({ cycleCloseDay: day })
        .where(eq(creditCards.id, card.id));
    }
  }
  if (parsed.paymentDueDate) {
    const day = Number(parsed.paymentDueDate.slice(8, 10));
    if (day >= 1 && day <= 28) {
      await db
        .update(creditCards)
        .set({ paymentDueDay: day })
        .where(eq(creditCards.id, card.id));
    }
  }

  const [batch] = await db
    .insert(importBatches)
    .values({
      type: "fatura",
      filename: file.name,
      warnings: parsed.warnings.join("\n"),
    })
    .returning();

  let createdPurchases = 0;
  for (const row of parsed.purchases) {
    const built = buildInstallments({
      installmentCount: row.installmentCount,
      amountPerInstallmentCents: row.amountPerInstallmentCents,
      currentNumber: row.currentNumber,
      currentCycleCloseIso: cycleClose,
    });

    const [purchase] = await db
      .insert(purchases)
      .values({
        creditCardId: card.id,
        merchant: row.merchant,
        purchaseDate: row.purchaseDate,
        totalCents: built.totalCents,
        installmentCount: row.installmentCount,
        status: "unconfirmed",
        importBatchId: batch.id,
      })
      .returning();

    await db.insert(installments).values(
      built.installments.map((inst) => ({
        purchaseId: purchase.id,
        number: inst.number,
        ofTotal: inst.ofTotal,
        amountCents: inst.amountCents,
        cycleCloseDate: inst.cycleCloseDate,
      })),
    );
    createdPurchases += 1;
  }

  return jsonOk({
    batch,
    created: { ledgerEntries: 0, purchases: createdPurchases },
    warnings: parsed.warnings,
    cycleCloseDate: cycleClose,
    paymentDueDate: parsed.paymentDueDate,
  });
}
