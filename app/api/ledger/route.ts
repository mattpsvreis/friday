import { eq } from "drizzle-orm";
import { db } from "@/db";
import { ledgerEntries } from "@/db/schema";
import {
  jsonError,
  jsonOk,
  readJson,
  unauthorizedIfNeeded,
} from "@/lib/api";

type LedgerBody = {
  id?: string;
  direction?: "income" | "expense";
  method?: (typeof ledgerEntries.$inferInsert)["method"];
  amountCents?: number;
  occursOn?: string;
  description?: string;
  categoryId?: string | null;
  creditCardId?: string | null;
};

function parseLedgerFields(body: LedgerBody, requireAll: boolean) {
  if (requireAll) {
    if (body.direction !== "income" && body.direction !== "expense") {
      return { error: "direction must be income or expense" as const };
    }
    if (!body.method) return { error: "method is required" as const };
    if (typeof body.amountCents !== "number") {
      return { error: "amountCents is required" as const };
    }
    if (!body.occursOn) return { error: "occursOn is required" as const };
  }

  return {
    values: {
      ...(body.direction !== undefined && { direction: body.direction }),
      ...(body.method !== undefined && { method: body.method }),
      ...(body.amountCents !== undefined && {
        amountCents: body.amountCents,
      }),
      ...(body.occursOn !== undefined && { occursOn: body.occursOn }),
      ...(body.description !== undefined && {
        description: body.description,
      }),
      ...(body.categoryId !== undefined && { categoryId: body.categoryId }),
      ...(body.creditCardId !== undefined && {
        creditCardId: body.creditCardId,
      }),
    },
  };
}

export async function GET(request: Request) {
  const unauthorized = await unauthorizedIfNeeded(request);
  if (unauthorized) return unauthorized;

  const direction = new URL(request.url).searchParams.get("direction");
  if (
    direction &&
    direction !== "income" &&
    direction !== "expense"
  ) {
    return jsonError("direction must be income or expense");
  }

  const rows =
    direction === "income" || direction === "expense"
      ? await db
          .select()
          .from(ledgerEntries)
          .where(eq(ledgerEntries.direction, direction))
      : await db.select().from(ledgerEntries);

  return jsonOk(rows);
}

export async function POST(request: Request) {
  const unauthorized = await unauthorizedIfNeeded(request);
  if (unauthorized) return unauthorized;

  const body = await readJson<LedgerBody>(request);
  const parsed = parseLedgerFields(body, true);
  if ("error" in parsed) return jsonError(String(parsed.error));

  const [created] = await db
    .insert(ledgerEntries)
    .values({
      ...parsed.values,
      direction: body.direction!,
      method: body.method!,
      amountCents: body.amountCents!,
      occursOn: body.occursOn!,
      description: body.description ?? "",
      status: "confirmed",
      autoGenerated: false,
    })
    .returning();

  return jsonOk(created);
}

export async function PUT(request: Request) {
  const unauthorized = await unauthorizedIfNeeded(request);
  if (unauthorized) return unauthorized;

  const body = await readJson<LedgerBody>(request);
  if (!body.id) return jsonError("id is required");
  const entryId = body.id;

  const parsed = parseLedgerFields(body, false);
  if ("error" in parsed) return jsonError(String(parsed.error));

  const [updated] = await db
    .update(ledgerEntries)
    .set(parsed.values)
    .where(eq(ledgerEntries.id, entryId))
    .returning();

  if (!updated) return jsonError("Entry not found", 404);
  return jsonOk(updated);
}

export async function DELETE(request: Request) {
  const unauthorized = await unauthorizedIfNeeded(request);
  if (unauthorized) return unauthorized;

  const id = new URL(request.url).searchParams.get("id");
  if (!id) return jsonError("id query parameter is required");

  await db.delete(ledgerEntries).where(eq(ledgerEntries.id, id));
  return jsonOk({ ok: true });
}
